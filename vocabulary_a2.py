class WordProgressTracker:
    def __init__(self, group_name: str = "group_1"):
        self.group_name = group_name
        self.group_words = VOCABULARY_DATA.get(group_name, [])
        self.total_in_group = len(self.group_words)  # 250 слов в группе
        self.passed_words = 0  # Счётчик пройденных слов

    def update_progress(self, count: int):
        """Добавляет пройденные слова с защитой от превышения лимита группы."""
        self.passed_words += count
        if self.passed_words > self.total_in_group:
            self.passed_words = self.total_in_group

    def get_percentage(self) -> float:
        """Считает процент: 25 слов из 250 = 10.0%"""
        if self.total_in_group == 0:
            return 0.0
        percentage = (self.passed_words / self.total_in_group) * 100
        return round(percentage, 1)

    def get_progress_text(self) -> str:
        pct = self.get_percentage()
        return f"Пройдено в группе: {self.passed_words} из {self.total_in_group} ({pct}%)"


